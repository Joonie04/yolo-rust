# Stage a Linux upload folder: copy only what build+run needs,
# dropping Windows artifacts / COCO train+test / .pt weights.
# Whitelist approach (copy only the good stuff), not robocopy exclusions.
#
# Usage (PowerShell):
#   powershell -NoProfile -ExecutionPolicy Bypass -File utils\stage_linux_upload.ps1
#   powershell -NoProfile -ExecutionPolicy Bypass -File utils\stage_linux_upload.ps1 -WithEval $true
param(
    [string]$Src = "D:\NEXT_LEVEL\Projects\yolo_rust",
    [string]$Dst = "D:\yolo_linux_upload",
    [bool]$WithEval = $false   # $true: also copy COCO val (~+1.5G) to re-run eval
)
$ErrorActionPreference = "Stop"

Write-Host "Cleaning old $Dst ..."
if (Test-Path $Dst) { Remove-Item -Recurse -Force $Dst }
New-Item -ItemType Directory -Path $Dst | Out-Null

# 1) source / config / build files
$dirs = @("src", "config", "vendor", "utils", "examples", "docs", "results", ".cargo")
foreach ($d in $dirs) { Copy-Item -Recurse (Join-Path $Src $d) (Join-Path $Dst $d) }
foreach ($f in @("Cargo.toml", "Cargo.lock", "build.rs", "README.md", ".gitignore", "CLAUDE.md")) {
    Copy-Item (Join-Path $Src $f) (Join-Path $Dst $f)
}

# 1b) Linux build config: drop the Windows-only [env] block.
#     Cargo's [env] cannot be scoped per-target, so the Windows FFMPEG_DIR / LIBCLANG_PATH
#     would otherwise leak onto Linux. On Linux everything is auto-detected (pkg-config for
#     FFmpeg, system libclang for bindgen), so this file just needs to exist with no [env].
$linuxCfg = @"
# Cargo build config for Linux (generated by utils/stage_linux_upload.ps1).
# The Windows dev config sets [env] FFMPEG_DIR / LIBCLANG_PATH for the `video` feature;
# Cargo cannot scope [env] per-platform, so that block is stripped here. On Linux, FFmpeg
# is found via pkg-config and libclang is auto-located -- no env vars needed.
"@
Set-Content -Path (Join-Path $Dst ".cargo\config.toml") -Value $linuxCfg -Encoding ASCII

# 2) models: copy whole tree, then delete .pt (Rust only uses .onnx)
Copy-Item -Recurse (Join-Path $Src "models") (Join-Path $Dst "models")
Get-ChildItem -Recurse (Join-Path $Dst "models") -Filter *.pt | Remove-Item -Force

# 3) data: everything except coco2017 (task sample images / bench / equiv, ~13M)
New-Item -ItemType Directory -Force -Path (Join-Path $Dst "data") | Out-Null
Get-ChildItem (Join-Path $Src "data") | Where-Object { $_.Name -ne "coco2017" } | ForEach-Object {
    Copy-Item -Recurse $_.FullName (Join-Path $Dst "data\$($_.Name)")
}

# 4) COCO val (optional)
if ($WithEval) {
    $coco = Join-Path $Dst "data\coco2017"
    New-Item -ItemType Directory -Force -Path $coco | Out-Null
    foreach ($sub in @("images", "labels", "annotations")) {
        Copy-Item -Recurse (Join-Path $Src "data\coco2017\$sub") (Join-Path $coco $sub)
    }
    Copy-Item (Join-Path $Src "data\coco2017\coco.yaml") (Join-Path $coco "coco.yaml")
}

$mb = (Get-ChildItem -Recurse $Dst | Measure-Object -Property Length -Sum).Sum / 1MB
Write-Host ("Done -> {0}  ({1:N1} MB)" -f $Dst, $mb)
